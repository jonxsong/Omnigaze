export const marketDashboardCopy = {
  en,
  "zh-CN": zh,
} satisfies Record<AppLocale, Record<DashboardCopyKey, string>>;

export function formatMarketDashboardCopy(
  locale: AppLocale,
  key: DashboardCopyKey,
  values: Record<string, string | number> = {},
) {
  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.replaceAll(`{${name}}`, String(value)),
    marketDashboardCopy[locale][key],
  );
}

