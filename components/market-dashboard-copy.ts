/** Localizes only stable, application-owned fixture IDs. Unknown/provider events pass through. */
export function localizeDemoIntelligenceEvent<T extends { id: string }>(
  locale: AppLocale,
  event: T,
): T | (T & DemoIntelligenceCopy) {
  if (locale !== "zh-CN") return event;
  const fixtureId = event.id.startsWith("demo:") ? event.id.slice(5) : event.id;
  const copy = chineseDemoIntelligenceById[fixtureId];
  return copy ? { ...event, ...copy } : event;
}

export type WatchlistSyncMessageCode = "save_failed" | "account_unavailable";

export function formatWatchlistSyncMessage(
  locale: AppLocale,
  code: WatchlistSyncMessageCode,
) {
  return code === "save_failed"
    ? `${formatMarketDashboardCopy(locale, "watchlistSaveFailed")} ${formatMarketDashboardCopy(locale, "lastChangeRollback")}`
    : formatMarketDashboardCopy(locale, "accountUnavailableChange");
}

